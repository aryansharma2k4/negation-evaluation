def phase2_scores(model_key: str = "minilm"):
    p1, p2 = load("phase1"), load("phase2")
    refsets = load_refsets()
    emb = embed([s for r in p1 + p2 for s in (r["a"], r["b"])], model_key)
    vemb = variant_embeddings([v["text"] for r in refsets.values()
                               for v in r["neg"] + r["same"]], model_key)
    axis, _ = fit_axis(p1, emb)
    X1, X2 = pair_features(p1, emb, axis), pair_features(p2, emb, axis)
    y1, y2 = labels(p1), labels(p2)
    a1, a2 = (arch2_scores(p1, emb, vemb, axis, refsets),
              arch2_scores(p2, emb, vemb, axis, refsets))

    def logistic(tr, te):
        mu, sd = tr.mean(axis=0), tr.std(axis=0) + 1e-9
        m = LogisticRegression(max_iter=5000).fit((tr - mu) / sd, y1)
        return m.predict_proba((tr - mu) / sd)[:, 1], m.predict_proba((te - mu) / sd)[:, 1]

    h1 = np.column_stack([X1, a1["margin_cos"], a1["margin_res"]])
    h2 = np.column_stack([X2, a2["margin_cos"], a2["margin_res"]])
    tr_h, te_h = logistic(h1, h2)
    nli = NLI()
    contra1 = nli.score([(r["a"], r["b"]) for r in p1])[:, 0]
    contra2 = nli.score([(r["a"], r["b"]) for r in p2])[:, 0]
    scores = {
        "arch3_hybrid": (te_h, best_threshold(y1, tr_h)),
        "arch2_cosine_margin": (a2["margin_cos"], best_threshold(y1, a1["margin_cos"])),
        "baseline_nli_contradiction": (contra2, best_threshold(y1, contra1)),
    }
    return p2, y2, X2, a2, scores


def examples(rows, y, X, a2, score, threshold, want, kind, n=15):
    picked = []
    order = np.argsort(-score if kind == "fp" else score)
    for i in order:
        if len(picked) >= n:
            break
        if kind == "fp" and y[i] == 0 and score[i] >= threshold:
            picked.append(int(i))
        if kind == "fn" and y[i] == 1 and score[i] < threshold:
            picked.append(int(i))
    print(head(["A", "B", "subtype/neg_type", "score", "delta_p", "c_raw", "c_resid",
                "cue_delta", "margin_cos"]))
    for i in picked:
        r = rows[i]
        print(row([r["a"].replace("|", "\\|"), r["b"].replace("|", "\\|"),
                   r["subtype"] if y[i] == 0 else (r["neg_type"] or "—"),
                   round(float(score[i]), 4), round(float(X[i, 2]), 3),
                   round(float(X[i, 3]), 3), round(float(X[i, 4]), 3),
                   int(X[i, 5]), round(float(a2["margin_cos"][i]), 3)]))
    return picked


def section_errors() -> None:
    rows, y, X, a2, scores = phase2_scores()
    print("<!-- generated by report_experiment2.py; scores recomputed from the "
          "cached embeddings and the same fitting code detect.py uses -->\n")
    for name in ("arch3_hybrid", "arch2_cosine_margin"):
        score, thr = scores[name]
        print(f"\n#### {NICE[name]} — 15 highest-scoring false positives "
              f"(threshold {round(thr, 4)})\n")
        examples(rows, y, X, a2, score, thr, None, "fp")
        print(f"\n#### {NICE[name]} — 15 lowest-scoring false negatives\n")
        examples(rows, y, X, a2, score, thr, None, "fn")

    print("\n#### Systematic patterns (counts over all 2,001 phase-2 pairs)\n")
    length = np.array([len(r["a"].split()) + len(r["b"].split()) for r in rows])
    buckets = [(0, 20), (20, 40), (40, 60), (60, 10_000)]
    for name in ("arch3_hybrid", "baseline_nli_contradiction"):
        score, thr = scores[name]
        pred = score >= thr
        print(f"\n*{NICE[name]}*\n")
        print(head(["pair length (words)", "n", "accuracy", "FPR", "recall"]))
        for lo, hi in buckets:
            sel = (length >= lo) & (length < hi)
            if sel.sum() == 0:
                continue
            yy, pp = y[sel], pred[sel]
            fpr = float(pp[yy == 0].mean()) if (yy == 0).any() else float("nan")
            rec = float(pp[yy == 1].mean()) if (yy == 1).any() else float("nan")
            print(row([f"{lo}–{hi if hi < 10_000 else '∞'}", int(sel.sum()),
                       round(float((pp == yy).mean()), 3), round(fpr, 3), round(rec, 3)]))

    hedges = re.compile(r"\b(may|might|could|probably|possibly|perhaps|likely|seems?)\b", re.I)
    multi = re.compile(r"\b(and|but|although|though|while|because)\b", re.I)
    print("\n*Feature-based slices, arch 3 hybrid*\n")
    score, thr = scores["arch3_hybrid"]
    pred = score >= thr
    slices = {
        "B contains a hedge word": np.array([bool(hedges.search(r["b"])) for r in rows]),
        "B is multi-clause": np.array([bool(multi.search(r["b"])) for r in rows]),
        "A already negated (cue in A)": np.array([cue_count(r["a"]) > 0 for r in rows]),
        "no cue anywhere in the pair": np.array([cue_count(r["a"]) == 0
                                                 and cue_count(r["b"]) == 0 for r in rows]),
    }
    print(head(["slice", "n", "n negations", "accuracy", "FPR", "recall"]))
    for name, sel in slices.items():
        yy, pp = y[sel], pred[sel]
        fpr = float(pp[yy == 0].mean()) if (yy == 0).any() else float("nan")
        rec = float(pp[yy == 1].mean()) if (yy == 1).any() else float("nan")
        print(row([name, int(sel.sum()), int((yy == 1).sum()),
                   round(float((pp == yy).mean()), 3), round(fpr, 3), round(rec, 3)]))

    print("\n*Quantified failure modes*\n")
    refsets = load_refsets()
    empty_neg = np.array([not refsets[r["a"]]["neg"] for r in rows])
    both_cued = np.array([cue_count(r["a"]) > 0 and cue_count(r["b"]) > 0 for r in rows])
    semanto = np.array([r["source"] == "antonym-substitution" for r in rows])
    wiki = np.array([r["source"] == "wikifactcheck-english" for r in rows])
    print(head(["claim", "count", "of", "share"]))
    for name in ("arch2_cosine_margin", "arch3_hybrid"):
        score, thr = scores[name]
        fn = (y == 1) & (score < thr)
        fp = (y == 0) & (score >= thr)
        print(row([f"{NICE[name]}: false negatives with an empty NEG set",
                   int((fn & empty_neg).sum()), int(fn.sum()),
                   round(float((fn & empty_neg).sum() / max(fn.sum(), 1)), 3)]))
        print(row([f"{NICE[name]}: false negatives where both A and B carry a cue",
                   int((fn & both_cued).sum()), int(fn.sum()),
                   round(float((fn & both_cued).sum() / max(fn.sum(), 1)), 3)]))
        print(row([f"{NICE[name]}: false positives that are SemAntoNeg paraphrases",
                   int((fp & semanto).sum()), int(fp.sum()),
                   round(float((fp & semanto).sum() / max(fp.sum(), 1)), 3)]))
    print(row(["pairs whose A has an empty NEG set", int(empty_neg.sum()), len(rows),
               round(float(empty_neg.mean()), 4)]))
    print(row(["recall on pairs with an empty NEG set (arch 2 cosine)",
               int(((y == 1) & empty_neg & (scores["arch2_cosine_margin"][0]
                    >= scores["arch2_cosine_margin"][1])).sum()),
               int(((y == 1) & empty_neg).sum()), "—"]))

    print("\n*Paraphrase false-positive rate by CANNOT source, phase 2*\n")
    print(head(["scorer", "SemAntoNeg paraphrases (n)", "FPR",
                "WikiFactCheck paraphrases (n)", "FPR"]))
    para = np.array([r["subtype"] == "paraphrase" for r in rows])
    for name in ("arch2_cosine_margin", "arch3_hybrid", "baseline_nli_contradiction"):
        score, thr = scores[name]
        pred = score >= thr
        cells = [NICE[name]]
        for mask in (semanto & para, wiki & para):
            cells += [int(mask.sum()), round(float(pred[mask].mean()), 3)]
        print(row(cells))

    print("\n#### Disagreements between the NLI baseline and arch 3 hybrid\n")
    s_h, t_h = scores["arch3_hybrid"]
    s_n, t_n = scores["baseline_nli_contradiction"]
    pred_h, pred_n = s_h >= t_h, s_n >= t_n
    for title, sel in (("NLI says negation, hybrid says not", pred_n & ~pred_h),
                       ("hybrid says negation, NLI says not", pred_h & ~pred_n)):
        idx = np.flatnonzero(sel)
        correct_nli = int((y[idx] == pred_n[idx]).sum())
        print(f"\n**{title}** — {len(idx)} pairs; NLI right on {correct_nli}, "
              f"hybrid right on {len(idx) - correct_nli}. Ten sampled (seed {SEED}):\n")
        rng = np.random.default_rng(SEED)
        take = rng.choice(idx, size=min(10, len(idx)), replace=False)
        print(head(["A", "B", "gold", "subtype", "NLI P(contra)", "hybrid P"]))
        for i in take:
            r = rows[int(i)]
            print(row([r["a"].replace("|", "\\|"), r["b"].replace("|", "\\|"),
                       "negation" if y[i] == 1 else "not negation", r["subtype"],
                       round(float(s_n[i]), 4), round(float(s_h[i]), 4)]))


