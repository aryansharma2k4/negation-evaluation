def section_data() -> None:
    p1, p2, ext = load("phase1"), load("phase2"), load("xnot360")
    print("<!-- generated by report_experiment2.py from data/*.jsonl -->\n")

    print("#### Counts per phase, class and subtype\n")
    print(head(["set", "pairs", "label 1 (negation)", "label 0", "subtypes"]))
    for name, rows in (("phase1", p1), ("phase2", p2), ("xnot360", ext)):
        c = Counter(r["subtype"] for r in rows)
        print(row([name, len(rows), sum(r["label"] == 1 for r in rows),
                   sum(r["label"] == 0 for r in rows),
                   ", ".join(f"{k}={v}" for k, v in sorted(c.items()))]))

    print("\n#### Counts per source dataset (CANNOT pairs only)\n")
    sources = sorted({r["source"] for r in p1 + p2 if r["dataset"] == "cannot"})
    print(head(["source", "phase1 neg", "phase1 para", "phase2 neg", "phase2 para"]))
    for s in sources:
        cells = [s]
        for rows in (p1, p2):
            for lab in (1, 0):
                cells.append(sum(1 for r in rows
                                 if r["source"] == s and r["label"] == lab))
        print(row(cells))

    print("\n#### Non-CANNOT negatives in phase 2\n")
    print(head(["subtype", "n", "source field values"]))
    for sub in ("sts_low", "snli_neutral", "random_pair"):
        rows = [r for r in p2 if r["subtype"] == sub]
        srcs = Counter(r["source"] for r in rows)
        print(row([sub, len(rows), ", ".join(f"{k}={v}" for k, v in srcs.most_common(4))]))

    print("\n#### Leakage check (recomputed here)\n")
    s1 = {norm(r[k]) for r in p1 for k in ("a", "b")}
    s2 = {norm(r[k]) for r in p2 for k in ("a", "b")}
    se = {norm(r[k]) for r in ext for k in ("a", "b")}
    print(head(["check", "result"]))
    print(row(["phase1 ∩ phase2 (normalised sentences)", len(s1 & s2)]))
    print(row(["phase1 ∩ xnot360", len(s1 & se)]))
    print(row(["phase2 ∩ xnot360", len(s2 & se)]))
    print(row(["distinct sentences phase1 / phase2 / xnot360",
               f"{len(s1)} / {len(s2)} / {len(se)}"]))
    print(row(["distinct A sentences phase1 / phase2",
               f"{len({norm(r['a']) for r in p1})} / {len({norm(r['a']) for r in p2})}"]))
    dup1 = len(p1) - len({(norm(r["a"]), norm(r["b"])) for r in p1})
    dup2 = len(p2) - len({(norm(r["a"]), norm(r["b"])) for r in p2})
    print(row(["duplicate (A,B) pairs within phase1 / phase2", f"{dup1} / {dup2}"]))

    print("\n#### Negation type of positives (derived, see §2)\n")
    print(head(["set", "verbal", "antonym", "other"]))
    for name, rows in (("phase1", p1), ("phase2", p2)):
        c = Counter(r["neg_type"] for r in rows if r["label"] == 1)
        print(row([name, c["verbal"], c["antonym"], c["other"]]))

    print("\n#### Data quality checks (recomputed here)\n")
    checks = []
    for name, rows in (("phase1", p1), ("phase2", p2), ("xnot360", ext)):
        checks.append([name, "A identical to B", sum(norm(r["a"]) == norm(r["b"]) for r in rows)])
        checks.append([name, "A or B under 20 characters",
                       sum(min(len(r["a"]), len(r["b"])) < 20 for r in rows)])
        checks.append([name, "B repeated across different A",
                       len(rows) - len({(norm(r["b"]), r["label"]) for r in rows})])
        checks.append([name, "pairs where A already contains a lexicon cue",
                       sum(cue_count(r["a"]) > 0 for r in rows)])
    print(head(["set", "check", "n"]))
    for c in checks:
        print(row(c))

    print("\n#### Ten randomly sampled pairs per class (verbatim)\n")
    rng = np.random.default_rng(SEED)
    groups = [("phase1 negation (label 1)", [r for r in p1 if r["label"] == 1]),
              ("phase1 paraphrase (label 0)", [r for r in p1 if r["label"] == 0]),
              ("phase2 negation (label 1)", [r for r in p2 if r["label"] == 1]),
              ("phase2 paraphrase (label 0)", [r for r in p2 if r["label"] == 0
                                               and r["subtype"] == "paraphrase"]),
              ("phase2 sts_low (label 0)", [r for r in p2 if r["subtype"] == "sts_low"]),
              ("phase2 snli_neutral (label 0)", [r for r in p2 if r["subtype"] == "snli_neutral"]),
              ("phase2 random_pair (label 0)", [r for r in p2 if r["subtype"] == "random_pair"]),
              ("xnot360 negation (label 1)", [r for r in ext if r["label"] == 1]),
              ("xnot360 not-negation (label 0)", [r for r in ext if r["label"] == 0])]
    for title, rows in groups:
        print(f"\n**{title}** (n={len(rows)}, 10 sampled with seed {SEED})\n")
        print(head(["A", "B", "source", "neg_type"]))
        for i in rng.choice(len(rows), size=min(10, len(rows)), replace=False):
            r = rows[int(i)]
            print(row([r["a"].replace("|", "\\|"), r["b"].replace("|", "\\|"),
                       r["source"], r["neg_type"] or "—"]))


