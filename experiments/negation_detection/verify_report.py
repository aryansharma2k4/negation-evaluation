def check(label, claim, truth):
    """The report rounds; a claim matches if it equals the value at its own precision."""
    global ok, bad
    try:
        c, t = float(claim), float(truth)
        dp = len(str(claim).split('.')[1]) if '.' in str(claim) else 0
        good = abs(round(t, dp) - c) < 10 ** -(dp + 3)
    except (TypeError, ValueError):
        good = str(claim) == str(truth)
    print(('OK  ' if good else 'BAD ') + f"{label}: report says {claim!r}, files say {truth!r}")
    ok, bad = ok + good, bad + (not good)

